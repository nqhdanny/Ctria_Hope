#!/bin/bash
set -e
export JAVA_HOME=/home/daniel/sdk/jdk-17.0.2
export ANDROID_HOME=/home/daniel/sdk/android-sdk
export PATH=$JAVA_HOME/bin:$ANDROID_HOME/build-tools/34.0.0:$ANDROID_HOME/platform-tools:$PATH
cd /home/daniel/hinge

ANDROID_JAR=$ANDROID_HOME/platforms/android-34/android.jar
BT=$ANDROID_HOME/build-tools/34.0.0

echo "### 0. 环境"
java -version 2>&1 | head -1

echo "### 1. 编译 HingeHelper（stub 只用于编译，不进产物）"
rm -rf work && mkdir -p work/classes work/dex
javac --release 8 -classpath "$ANDROID_JAR" -d work/classes \
  patch/stub/org/citra/emu/NativeLibrary.java \
  patch/stub/org/citra/emu/overlay/InputOverlay.java \
  patch/HingeHelper.java \
  patch/BundledGames.java \
  patch/StorageGate.java \
  patch/SettingsSkin.java \
  patch/AgCompliance.java
ls -l work/classes/org/citra/emu/

echo "### 2. dex 化（HingeHelper 及其全部内部类，排除编译用 stub）"
CLS=$(find work/classes -name '*.class' | grep -v 'NativeLibrary' | grep -v 'overlay/InputOverlay')
echo "$CLS"
$BT/d8 --min-api 24 --lib "$ANDROID_JAR" --output work/dex $CLS
ls -l work/dex

echo "### 2.4 剥离主机数据 / 密钥 / 固件（审核红线，也是法律红线）"
# 上游 MMJ 为了"开箱即用"，把从真机 dump 出来的东西打进了 assets：
#   sysdata/aes_keys.txt   3DS AES 密钥表（KeyX / KeyY）
#   sysdata/*.bcfnt        3DS 系统字体，10.8 MB
#   nand/**                NAND 里的系统 title 与 sysdata
#   sdmc/**                模拟 SD 卡里的 luma 插件、DSP 固件 dspfirm.cdc、PKSM 资源
# 这些是任天堂的主机固件与密钥，不是本项目的代码：分发它们等于分发绕过技术保护
# 措施的工具，Google Play / AppGallery 都是直接驳回（且可被权利人投诉）。
# 删掉之后：开源 .3dsx 照样能跑；商业游戏需要用户自己按 Citra 官方姿势提供
# citra-emu/sysdata/aes_keys.txt —— 这也是本项目一直声明的法律立场。
rm -rf dec/assets/sysdata dec/assets/nand dec/assets/sdmc
mkdir -p dec/assets/sysdata
cat > dec/assets/sysdata/README.txt <<'SYSDOC'
No system files are bundled with this application.

This folder used to ship an AES key table and the console system fonts.
Both belong to the console vendor, not to this project, so they were removed.

If you own a console and have dumped its keys and shared fonts yourself,
place them here (or in citra-emu/sysdata on your storage) exactly as the
upstream emulator expects:

    aes_keys.txt            AES key table
    cbf_std.bcfnt           shared system font

Without them, encrypted titles cannot be decrypted and some games will show
blank text. Homebrew and unencrypted titles are unaffected.
SYSDOC
du -sh dec/assets 2>/dev/null

echo "### 2.5 清理上一版残留的壁纸（用户要求去掉碳纤维背景）"
rm -f dec/assets/wallpaper.jpg

echo "### 2.6 内置开源免费游戏（MIT，许可证随包）"
mkdir -p dec/assets/config
cp patch/assets_config/config-mmj.ini dec/assets/config/config-mmj.ini
# 按键标定值必须随包走，否则用户拿到的是上游默认布局（L/R 位置全错）
cp patch/input-layout.ini dec/assets/config/input-layout.ini
# 必须先清空：dec/ 是长期复用的反编译树，上一版删掉的游戏不清会一直留在包里
rm -rf dec/assets/free-games
mkdir -p dec/assets/free-games
cp free-games/*.3dsx dec/assets/free-games/
python3 - <<'PY'
import io, os
src = 'free-games/licenses'
names = [('TRexGame-LICENSE.txt', 'T-Rex Game 3DS — https://github.com/BlyZeDev/T-Rex-Game-3DS'),
         ('2048-LICENSE.txt',     '2048 for 3DS — https://github.com/0rientd/2048-port-3ds')]
out = ['Bundled free / open-source homebrew for Citra',
       'Released here as unmodified builds from the upstream GitHub releases.',
       '']
for fn, head in names:
    p = os.path.join(src, fn)
    out.append('=' * 72)
    out.append(head)
    out.append('=' * 72)
    out.append(io.open(p, encoding='utf-8', errors='replace').read().strip())
    out.append('')
io.open('dec/assets/free-games/LICENSES.txt', 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('LICENSES.txt', os.path.getsize('dec/assets/free-games/LICENSES.txt'), 'bytes')
PY
ls -l dec/assets/free-games/

echo "### 2.7 把 8 套面板主题合进 APK（首启由 BundledGames 解到 /sdcard/citra-emu/theme）"
rm -rf dec/assets/themes && mkdir -p dec/assets/themes
cp themes/*.zip dec/assets/themes/
{
  echo "Bundled panel themes for Citra Hinge"
  echo ""
  echo "These zip files are original artwork generated by this project"
  echo "(skins_panel.py / skins_design.py) and are released under GPL-2.0,"
  echo "same as the rest of this patch."
  echo ""
  echo "They are extracted to /sdcard/citra-emu/theme/ on first launch and"
  echo "can be picked in Settings - Core - Theme, or replaced at will."
} > dec/assets/themes/README.txt
ls -l dec/assets/themes/ | tail -3
du -sh dec/assets/themes

echo "### 2.8 随包许可文件（GPL-2.0 §1 要求：分发二进制必须附带许可全文）"
python3 patch/gen_licenses.py | tail -8

echo "### 2.9 应用内隐私政策（华为审核要求"可访问"，且要与权限逐条对得上）"
python3 patch/gen_privacy.py | tail -3

echo "### 2.10 自有图标（上游图标是 Citra 的品牌资产，GPL 不含商标）"
# patch/icons/ 里是已渲染好的成品；只有在装了 Pillow 的机器上才现场重绘
if python3 -c "import PIL" 2>/dev/null; then
  python3 patch/gen_icons.py | tail -2
else
  echo "  (Pillow 缺失，使用 patch/icons/ 中的成品)"
fi
for d in mdpi hdpi xhdpi xxhdpi xxxhdpi; do
  cp patch/icons/mipmap-$d/ic_citra.png dec/res/mipmap-$d/ic_citra.png
  cp patch/icons/mipmap-$d/ic_launcher_foreground.png dec/res/mipmap-$d/ic_launcher_foreground.png
done
ls -l dec/res/mipmap-xxxhdpi/ic_citra.png dec/res/mipmap-xxxhdpi/ic_launcher_foreground.png

echo "### 3. 锁竖屏 + 注入 smali"
python3 patch/patch_manifest.py | head -6
python3 patch/patch_smali.py | head -3
python3 patch/patch_games.py | head -14
python3 patch/patch_storage.py | head -3
python3 patch/patch_settings.py | head -6
python3 patch/patch_dialog.py | head -4
python3 patch/patch_running.py | head -3
python3 patch/patch_ag34_manifest.py | head -4
# applicationId: org.citra.emu -> com.ctriahope.emu（类包名保持不动，JNI 依赖）
python3 patch/patch_package.py
python3 patch/patch_ag34.py
python3 patch/patch_about.py | head -8
python3 patch/patch_ag_compliance.py
python3 patch/patch_crash_guard.py
python3 patch/patch_crash_guard2.py

echo "### 4. apktool 重新打包"
java -Xmx4g -jar apktool.jar b dec -o work/rebuilt.apk > work/build.log 2>&1 || { tail -25 work/build.log; exit 1; }
tail -4 work/build.log
ls -l work/rebuilt.apk

echo "### 5. 追加 classes2.dex"
python3 - <<'PY'
import zipfile
src = 'work/rebuilt.apk'
dst = 'work/unsigned.apk'
helper = open('work/dex/classes.dex', 'rb').read()
zin = zipfile.ZipFile(src)
names = [i.filename for i in zin.infolist()]
assert 'classes2.dex' not in names, '已存在 classes2.dex'
zout = zipfile.ZipFile(dst, 'w')
for it in zin.infolist():
    zout.writestr(it, zin.read(it.filename))
zi = zipfile.ZipInfo('classes2.dex')
zi.compress_type = zipfile.ZIP_DEFLATED
zout.writestr(zi, helper)
zout.close()
print('dex 数:', sum(1 for n in names if n.endswith('.dex')), '+1')
PY

echo "### 6. 对齐 + 签名"
# 密钥路径与口令走环境变量：KS_FILE / KS_PASS（仓库里不存任何密钥材料）
[ -f "$KS_FILE" ] || { echo "ERR: keystore $KS_FILE not found"; exit 1; }
$BT/zipalign -f -p 4 work/unsigned.apk work/aligned.apk
$BT/apksigner sign --ks "$KS_FILE" --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" \
  --v1-signing-enabled true --v2-signing-enabled true --out citra-hinge.apk work/aligned.apk
$BT/apksigner verify --print-certs citra-hinge.apk | head -3
ls -l citra-hinge.apk
echo "### DONE"
